// Единственное место с селекторами Авито. Все они проверены на живом сайте 21.08.2026:
// в скобках — сколько карточек из 50 отдали элемент на выдаче «iPhone 13».
globalThis.AC = globalThis.AC || {};

AC.CFG = {
  SEL: {
    // Единственный подтверждённый root обычной поисковой выдачи.
    searchRoot: '[data-marker="catalog-serp"]',
    // Карта — отдельный контекст, parser обычной выдачи там не запускается.
    mapPage: '[data-marker="map-full"], [data-marker="map-view"]',
    // Страница объявления считается подтверждённой только после появления
    // одного из собственных item-view markers, а не по похожему URL.
    itemPage: '[data-marker="item-view/title-info"], [data-marker="item-view/item-price"]',
    // карточка выдачи (50/50)
    card: '[data-marker="item"]',
    // ссылка-заголовок, из неё берём id объявления (50/50)
    title: '[data-marker="item-title"]',
    // цена: в content= лежит чистое число (50/50)
    price: '[itemprop="price"]',
    // Блок продавца рисуется ТОЛЬКО у профессиональных продавцов с витриной.
    // У частника его нет вообще — это и есть признак. Параметр search_seller_info
    // отличает ссылку продавца от хлебных крошек вида /brands/apple.
    sellerLink: 'a[href*="search_seller_info"]',
    sellerReviews: '[data-marker="seller-info/summary"]',
    // Авито само рисует на фото метку «Просмотрено», если вы уже открывали
    // объявление. Читаем её как подсказку — тогда расширение начинает работать
    // с первой же страницы, не дожидаясь, пока накопится собственная история.
    photo: '[data-marker="item-image"]'
  },

  VIEWED_TEXT: 'Просмотрено',

  // Признак профессионального продавца одинаков во всех разделах, а вот слово —
  // нет. На вакансиях «магазин» это враньё: там работодатель, на недвижимости —
  // агентство. Проверено на живой выдаче: вакансии 46 профи из 50, авто 47 из 50.
  // Первое совпадение по адресу побеждает, иначе «магазин».
  SELLER_WORDS: [
    [/\/(vakansii|rezume|rabota)/, 'работодатель'],
    [/\/(kvartiry|komnaty|doma_dachi|zemelnye|garazhi|kommercheskaya|nedvizhimost)/, 'агентство'],
    [/\/(avtomobili|gruzoviki|motocikly|vodnyy_transport|spectehnika)/, 'автосалон'],
    [/\/(predlozheniya_uslug|uslugi)/, 'компания']
  ],
  SELLER_WORD_DEFAULT: 'магазин',

  // Родной фильтр Авито «Продавцы: Все / Частные / Компании» — это параметр
  // user в адресе выдачи: 0 — все, 1 — частные, 2 — компании. Значения взяты
  // не из головы: у радиогруппы data-marker="user" опции user/option(0|1|2)
  // несут ровно эти value. Проверено живьём 21.08.2026 на выдаче «iPhone 16»:
  // дописанный &user=1 отмечает радио «Частные», счётчик падает с 3 502 до
  // 2 223, ссылки пагинации параметр сохраняют, а в разделах без такого
  // фильтра (аренда квартир) Авито его молча игнорирует и ничего не ломает.
  //
  // Зачем он нам. Скрывать на клиенте бессмысленно: выдача «iPhone 16» без
  // фильтра отдаёт 47 витрин из 50, медиана 868 отзывов, продавцов с 20 и
  // меньше отзывами на первой странице НОЛЬ — гасить нечего, экран пустеет,
  // а следующая страница приходит такой же. С user=1 таких продавцов уже
  // 15 из 50, медиана 79. Плотную выдачу может дать только сервер.
  PRIVATE_FILTER: { param: 'user', value: '1' },

  // Сколько раз пробуем поставить параметр на один и тот же поиск.
  // Проверено, что Авито его сохраняет, но это обещание чужой площадки: если
  // в каком-то разделе она параметр выкинет при загрузке, мы увидим адрес без
  // него, поставим снова — и так до бесконечности. Вторая попытка это ловит,
  // дальше работаем без родного фильтра, гашением на клиенте.
  MAX_FILTER_TRIES: 2,

  // Страховка на случай, если браузер отказал в переходе (Chrome умеет
  // придушить серию навигаций). Через столько миллисекунд снимаем внутренний
  // стоп-флаг и рисуем по тому DOM, который есть, вместо вечного ожидания.
  NAVIGATION_TIMEOUT_MS: 5000,

  // Что считаем «не частником». Родной фильтр Авито делит продавцов по форме
  // регистрации, поэтому под «Частные» спокойно живут OOO «ЗЛЫЕ МАРСИАНЕ»,
  // «Apple Store | Komarova Plaza» и «Скупка цифровой техники» с 1 470
  // отзывами. Юридическую форму мы не видим и видеть не можем — судим по
  // следам работы: витрина, гора отзывов, несколько мест в одной выдаче.
  PRO: {
    // Витрина /brands/ — сам Авито считает продавца профессиональным.
    SHOWCASE: true,
    // 20 отзывов частник за жизнь набирает редко; на выдаче «iPhone 16»
    // порог оставляет видимыми 11 карточек из 50 — страница не пустая.
    MIN_REVIEWS: 20,
    // Три и больше объявления в одной выдаче — это уже поток, а не «продаю своё».
    MIN_LISTINGS: 3
  },

  // Пауза перед перерисовкой после изменений DOM.
  DEBOUNCE_MS: 200,

  // Потолок ожидания: даже если страница дёргается непрерывно,
  // отрисовка обязана случиться не реже, чем раз в секунду.
  DEBOUNCE_MAX_MS: 1000,

  // Просмотренные забываем через месяц, чтобы хранилище не пухло.
  SEEN_TTL_DAYS: 30,

  DEFAULTS: {
    hideShops: false
  }
};
